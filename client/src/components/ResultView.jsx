import React from 'react';

export function ResultView({ result, subjects }) {
  return (
    <div className="print-page">
      <div className="mb-4 rounded-md bg-amber-50 dark:bg-amber-950/40 border border-amber-300 dark:border-amber-800 p-3 text-xs text-amber-800 dark:text-amber-300">
        STUDENT-GENERATED RESULT REPORT — Generated by SGBAU Result Watch. This is NOT an official
        university certificate. ResultWatch is not affiliated with SGBAU.
      </div>

      <h1 className="text-xl font-bold">SGBAU Result Report</h1>
      <p className="text-sm text-gray-500 mb-4">Sant Gadge Baba Amravati University</p>

      <h2 className="font-semibold border-b border-gray-300 dark:border-gray-700 pb-1 mt-6 mb-2 uppercase text-sm tracking-wide">
        Student Details
      </h2>
      <dl className="grid grid-cols-2 gap-x-6 gap-y-1 text-sm">
        <Row label="Roll Number" value={result.roll_number} />
        <Row label="Course" value={result.course} />
        <Row label="Branch" value={result.branch} />
        <Row label="Curriculum" value={result.curriculum} />
        <Row label="Semester" value={result.semester} />
        <Row label="Exam" value={result.profile_exam_type} />
        <Row label="Session" value={result.profile_exam_session} />
        <Row label="Academic Year" value={result.academic_year} />
        <Row label="Result Date" value={result.result_date} />
      </dl>

      <h2 className="font-semibold border-b border-gray-300 dark:border-gray-700 pb-1 mt-6 mb-2 uppercase text-sm tracking-wide">
        Subject Details
      </h2>
      <table className="w-full text-sm border-collapse">
        <thead>
          <tr className="text-left bg-gray-50 dark:bg-gray-800/60">
            {['Code', 'Subject', 'Credits', 'Internal', 'External', 'Total', 'Grade', 'GP', 'Status'].map((h) => (
              <th key={h} className="border border-gray-200 dark:border-gray-700 p-2">{h}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {subjects.length === 0 ? (
            <tr><td colSpan={9} className="p-3 text-center text-gray-500 border border-gray-200 dark:border-gray-700">No subject-wise data available.</td></tr>
          ) : (
            subjects.map((s) => (
              <tr key={s.id}>
                {[s.subject_code, s.subject_name, s.credits, s.internal_marks, s.external_marks, s.total_marks, s.grade, s.grade_point, s.status].map((v, i) => (
                  <td key={i} className="border border-gray-200 dark:border-gray-700 p-2">{v ?? '—'}</td>
                ))}
              </tr>
            ))
          )}
        </tbody>
      </table>

      <h2 className="font-semibold border-b border-gray-300 dark:border-gray-700 pb-1 mt-6 mb-2 uppercase text-sm tracking-wide">
        Result Summary
      </h2>
      <div className="grid grid-cols-4 gap-3">
        <Summary label="SGPA" value={result.sgpa} />
        <Summary label="CGPA" value={result.cgpa} />
        <Summary label="Percentage" value={result.percentage} />
        <Summary label="Backlogs" value={result.backlogs ?? 0} />
      </div>

      <p className="text-xs text-gray-400 mt-6">Final Result: {result.result_status}</p>
    </div>
  );
}

function Row({ label, value }) {
  return (
    <>
      <dt className="text-gray-500">{label}</dt>
      <dd className="font-medium">{value || '—'}</dd>
    </>
  );
}

function Summary({ label, value }) {
  return (
    <div className="rounded-lg border border-gray-200 dark:border-gray-700 p-3 text-center">
      <div className="text-lg font-bold">{value ?? '—'}</div>
      <div className="text-xs text-gray-500 uppercase tracking-wide">{label}</div>
    </div>
  );
}
