function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function fmt(v, fallback = '—') {
  return v === null || v === undefined || v === '' ? fallback : escapeHtml(v);
}

function subjectRows(subjects) {
  if (!subjects || subjects.length === 0) {
    return `<tr><td colspan="8" class="empty">No subject-wise data was available from the source.</td></tr>`;
  }
  return subjects
    .map(
      (s) => `
      <tr>
        <td>${fmt(s.subject_code)}</td>
        <td>${fmt(s.subject_name)}</td>
        <td>${fmt(s.credits)}</td>
        <td>${fmt(s.internal_marks)}</td>
        <td>${fmt(s.external_marks)}</td>
        <td>${fmt(s.total_marks)}</td>
        <td>${fmt(s.grade)}</td>
        <td>${fmt(s.grade_point)}</td>
      </tr>`
    )
    .join('');
}

